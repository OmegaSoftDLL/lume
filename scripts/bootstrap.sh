#!/bin/sh
# Lume staged, self-verifying bootstrap — the GCC/Rust/Go model.
#
#   Stage 0  the FROZEN C seed (bootstrap/lume0) mints the first Lume tools.
#            This is the only step that uses C, exactly as GCC needs a system
#            C compiler and Rust needs a prior rustc. lume0 is kept as the
#            reproducibility root; it is never on the steady-state path.
#   Stage 1  the seed-built tools rebuild the toolchain from Lume source — NO C.
#   Stage 2  the stage-1 tools rebuild it again (pure Lume building pure Lume).
#   Stage 3  once more, then assert STAGE 2 == STAGE 3, bit for bit.
#
# Comparing stage 2 to stage 3 (not stage 1) is deliberate and is what GCC does:
# stage 1 is produced along a seed-influenced path, so the fixpoint is the point
# from which the Lume-built tools reproduce themselves exactly.
set -eu
cd "$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)"

# The self-hosted lexer/parser recurse once per source character, so compiling the
# ~117 KB compiler consumes a deep native stack. Raise the stack limit so a growing
# compiler source does not overflow the default 8 MB stack (a SIGSEGV in stage 1).
ulimit -s unlimited 2>/dev/null || ulimit -s 524288 2>/dev/null || true

SRC=compiler/stage1
L0=bootstrap/lume0/lume0
OUT=${1:-build/bootstrap}
mkdir -p "$OUT"

# compiler/stage1/lumec.src is GENERATED by amalgamating compiler/stage1/lume/*.src;
# regenerate it before the seed compiles it (byte-identical to the historical file,
# so the stage 2 == stage 3 fixpoint is untouched).
sh scripts/amalgamate.sh

echo "== Stage 0: frozen C seed mints lumec + lasm =="
make -s -C bootstrap/lume0
"$L0" run "$SRC/data_asm_cc.lume" "$SRC/lumec.src" "$OUT/lumec0.s"
"$L0" asm "$OUT/lumec0.s" "$OUT/lumec0"
"$L0" run "$SRC/data_asm_cc.lume" "$SRC/lasm.src" "$OUT/lasm0.s"
"$L0" asm "$OUT/lasm0.s" "$OUT/lasm0"

# stage N: use $1=lumec $2=lasm to build the next lumec+lasm into $3_*
stage() {
  _lc=$1; _la=$2; _tag=$3
  "$_lc" < "$SRC/lumec.src" > "$OUT/lumec$_tag.s"
  "$_la" < "$OUT/lumec$_tag.s" > "$OUT/lumec$_tag"; chmod +x "$OUT/lumec$_tag"
  "$_lc" < "$SRC/lasm.src"  > "$OUT/lasm$_tag.s"
  "$_la" < "$OUT/lasm$_tag.s"  > "$OUT/lasm$_tag";  chmod +x "$OUT/lasm$_tag"
}

echo "== Stage 1: Lume rebuilds Lume (no C) =="
stage "$OUT/lumec0" "$OUT/lasm0" 1
echo "== Stage 2: Lume-built tools rebuild again =="
stage "$OUT/lumec1" "$OUT/lasm1" 2
echo "== Stage 3: once more =="
stage "$OUT/lumec2" "$OUT/lasm2" 3

echo "== Fixpoint check: stage 2 == stage 3 (bit for bit) =="
cmp "$OUT/lumec2.s" "$OUT/lumec3.s"
cmp "$OUT/lumec2"   "$OUT/lumec3"
cmp "$OUT/lasm2.s"  "$OUT/lasm3.s"
cmp "$OUT/lasm2"    "$OUT/lasm3"

echo "== Sanity: the self-built toolchain compiles and runs a program =="
echo 'fn fib(n) = if n < 2 then n else fib(n - 1) + fib(n - 2)
print fib(10)' > "$OUT/t.src"
"$OUT/lumec3" < "$OUT/t.src" | "$OUT/lasm3" > "$OUT/t"; chmod +x "$OUT/t"
test "$("$OUT/t")" = "55"

echo "OK: Lume is self-hosted — stages 1-3 use NO C, and stage 2 == stage 3 bit-identically."
