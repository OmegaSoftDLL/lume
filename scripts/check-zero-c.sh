#!/bin/sh
# Prove the ZERO-C STEADY STATE, adversarially.
#
# Lume's bootstrap uses C in exactly one place: Stage 0, where the frozen seed
# `bootstrap/lume0` (a small C interpreter + its own ELF writer) mints the first
# Lume-built tools. That seed is kept DELIBERATELY as the auditable,
# reproducible-from-source root (see docs/04-roadmap.md and docs/14-zero-c.md) —
# exactly as GCC needs a system C compiler and Rust needs a prior rustc. It is
# never on the steady-state path.
#
# This script proves the steady state really is C-free. After the seed has
# minted lumec0/lasm0, it SHADOWS every C compiler and external assembler/linker
# (cc, gcc, clang, c++, g++, as, ld) with stubs that FAIL LOUDLY if invoked, and
# then runs bootstrap stages 1-3 — Lume compiling Lume, assembled to native ELF
# by `lasm` (written in Lume), with NO as/ld. If any C or external as/ld had
# crept into the steady state, a stub would fire and the build would fail. The
# run ends by asserting the stage 2 == stage 3 fixpoint, bit for bit.
set -eu
cd "$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)"

# Deep per-character recursion in the self-hosted lexer/parser needs a large stack.
ulimit -s unlimited 2>/dev/null || ulimit -s 524288 2>/dev/null || true

SRC=compiler/stage1
L0=bootstrap/lume0/lume0
OUT=${1:-build/zero-c}
SHIM="$OUT/shim"
rm -rf "$OUT"
mkdir -p "$SHIM"

# compiler/stage1/lumec.src is generated by amalgamating compiler/stage1/lume/*.src.
sh scripts/amalgamate.sh

echo "== Seed freeze check (#205): verify bootstrap/lume0/*.c and *.h are strictly frozen =="
if command -v sha256sum >/dev/null 2>&1; then
  sha256sum -c bootstrap/lume0/SEED_FREEZE.sha256
elif command -v shasum >/dev/null 2>&1; then
  shasum -a 256 -c bootstrap/lume0/SEED_FREEZE.sha256
else
  echo "zero-c: neither sha256sum nor shasum found to verify SEED_FREEZE.sha256" >&2
  exit 1
fi

echo "== Seed (C allowed here, and ONLY here): build lume0 and mint lumec0 + lasm0 =="
make -s -C bootstrap/lume0
"$L0" run "$SRC/data_asm_cc.lume" "$SRC/lumec.src" "$OUT/lumec0.s"
"$L0" asm "$OUT/lumec0.s" "$OUT/lumec0"
"$L0" run "$SRC/data_asm_cc.lume" "$SRC/lasm.src" "$OUT/lasm0.s"
"$L0" asm "$OUT/lasm0.s" "$OUT/lasm0"

echo "== Shadow the C toolchain: cc/gcc/clang/c++/g++/as/ld now fail if invoked =="
for t in cc gcc clang c++ g++ as ld; do
  cat > "$SHIM/$t" <<EOF
#!/bin/sh
echo "ZERO-C VIOLATION: the steady-state build invoked '$t' $*" >&2
exit 97
EOF
  chmod +x "$SHIM/$t"
done
PATH="$(cd "$SHIM" && pwd):$PATH"
export PATH
# Confirm the shims really are first on PATH (otherwise the proof is vacuous).
for t in cc as ld; do
  resolved=$(command -v "$t" || true)
  case "$resolved" in
    "$(cd "$SHIM" && pwd)/$t") : ;;
    *) echo "zero-c: shim for '$t' not active (resolved: ${resolved:-none}); aborting"; exit 1 ;;
  esac
done

# stage N: use $1=lumec $2=lasm to build the next lumec+lasm+lcli into $OUT/*$3.
# Identical to scripts/bootstrap.sh — only Lume binaries run; no cc/as/ld.
stage() {
  _lc=$1; _la=$2; _tag=$3
  "$_lc" < "$SRC/lumec.src" > "$OUT/lumec$_tag.s"
  "$_la" < "$OUT/lumec$_tag.s" > "$OUT/lumec$_tag"; chmod +x "$OUT/lumec$_tag"
  "$_lc" < "$SRC/lasm.src"  > "$OUT/lasm$_tag.s"
  "$_la" < "$OUT/lasm$_tag.s"  > "$OUT/lasm$_tag";  chmod +x "$OUT/lasm$_tag"
  "$_lc" < "$SRC/lcli.src"  > "$OUT/lcli$_tag.s"
  "$_la" < "$OUT/lcli$_tag.s"  > "$OUT/lcli$_tag";  chmod +x "$OUT/lcli$_tag"
}

echo "== Stage 1: Lume rebuilds Lume (C toolchain shadowed) =="
stage "$OUT/lumec0" "$OUT/lasm0" 1
echo "== Stage 2: Lume-built tools rebuild again =="
stage "$OUT/lumec1" "$OUT/lasm1" 2
echo "== Stage 3: once more =="
stage "$OUT/lumec2" "$OUT/lasm2" 3

echo "== Fixpoint check under the shadowed toolchain: stage 2 == stage 3 =="
cmp "$OUT/lumec2.s" "$OUT/lumec3.s"
cmp "$OUT/lumec2"   "$OUT/lumec3"
cmp "$OUT/lasm2.s"  "$OUT/lasm3.s"
cmp "$OUT/lasm2"    "$OUT/lasm3"
cmp "$OUT/lcli2.s"  "$OUT/lcli3.s"
cmp "$OUT/lcli2"    "$OUT/lcli3"

echo "== Sanity: the C-free toolchain compiles and runs a program (assembled by lasm, no as/ld) =="
printf 'fn fib(n) = if n < 2 then n else fib(n - 1) + fib(n - 2)\nprint fib(10)\n' > "$OUT/t.src"
"$OUT/lumec3" < "$OUT/t.src" | "$OUT/lasm3" > "$OUT/t"; chmod +x "$OUT/t"
test "$("$OUT/t")" = "55"

echo "OK: zero-C steady state proven — stages 1-3 built Lume-with-Lume and assembled"
echo "    native ELF with lasm; cc/gcc/clang/as/ld were never invoked; stage 2 == stage 3."
